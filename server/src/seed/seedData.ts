export function initializeStoreIfEmpty(store: {
  isEmpty: () => boolean;
  resetWithData: (data: { agents: Agent[]; tasks: Task[]; contextEntries: ContextEntry[] }, events: AuditEvent[]) => void;
}): void {
  if (store.isEmpty()) {
    const seed = createInitialSeedData();
    store.resetWithData(
      {
        agents: seed.agents,
        tasks: seed.tasks,
        contextEntries: seed.contextEntries,
      },
      seed.events
    );
    console.log('[SamparkSeed] Initialized store with seed data.');
  }
}
